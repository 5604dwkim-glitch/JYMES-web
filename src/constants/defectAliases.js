/** 분류 접두사 + 항목명이 함께 있어야 의미가 보존되는 항목 (접두사 제거 전에 처리) */
const CATEGORY_SPECIFIC_LABELS = {
  '[검사/조인트] 불량': '조인트불량',
  '[검사_조인트] 불량': '조인트불량',
  '[검사/소재] 클립누락_소재': '클립누락(소재)',
  '[검사/성형] 클립누락_성형': '클립누락(성형)',
  '[검사_소재] 클립누락_소재': '클립누락(소재)',
  '[검사_성형] 클립누락_성형': '클립누락(성형)'
};

/**
 * 저장된 불량 키(분류 접두사 포함)를 통계용 표준명으로 변환한다.
 * 이미 표준명인 값도 그대로 통과(멱등)한다.
 */
export function normalizeDefectName(rawName) {
  let s = String(rawName || '').trim();
  if (!s) return s;
  if (CATEGORY_SPECIFIC_LABELS[s]) return CATEGORY_SPECIFIC_LABELS[s];
  s = s.replace(/^\[[^\]]*\]\s*/, '').trim();
  return DEFECT_LABEL_ALIASES[s] || s;
}
